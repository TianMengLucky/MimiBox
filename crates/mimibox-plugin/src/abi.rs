//! 插件 ABI 约定：版本号、字符串所有权与 JSON 信封格式。
//!
//! 跨 FFI 边界的字符串统一遵循「谁分配谁释放」：
//! - 同步调用（vtable 函数、`mb_plugin_invoke`）的入参由调用方分配，
//!   调用返回后由调用方释放，被调方只读；
//! - 被调方返回的字符串由被调方分配（`CString::into_raw`），调用方读取后
//!   通过对方的 `free_string`（宿主侧）或 `mb_free_string`（插件侧）释放；
//! - 异步命令的完成回调（`done`）中传出的字符串仅在回调执行期间有效，
//!   回调返回后由插件侧释放。

/// 插件 ABI 版本：宿主与插件必须一致才会加载。
/// 任何 C ABI / vtable 布局 / 信封格式变更时 +1 并同步更新宿主校验。
pub const MB_ABI_VERSION: u32 = 1;
